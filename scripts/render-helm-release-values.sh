#!/usr/bin/env bash
set -euo pipefail

# Render the Helm values fragment that pins the chart to the container image a
# release just published.
#
# The chart itself is not packaged or published: it lives in the repository
# under deploy/helm/lazy-observe. The digest of the pushed multi-architecture
# image only exists after docker/build-push-action runs, which is after
# GoReleaser has created the GitHub Release, so the release workflow renders
# this fragment from steps.build.outputs.digest and attaches it to the release
# as helm-values-lazy-observe-<version>.yaml. Deployers layer it on top of the
# chart:
#
#   helm upgrade --install lazy-observe deploy/helm/lazy-observe \
#     -f helm-values-lazy-observe-<version>.yaml
#
# Usage:
#   render-helm-release-values.sh --tag <version> --digest <sha256:...>
#     [--repository <repo>] [--output <file>]
#
# Without --output the fragment goes to stdout. The digest is validated with the
# same rule the chart template enforces, so a truncated or malformed digest -
# for example from a changed action output name - fails here instead of
# producing a values file that silently pulls a mutable tag.

usage() {
  printf 'usage: %s --tag <version> --digest sha256:<64 hex> [--repository <repo>] [--output <file>]\n' \
    "${0##*/}" >&2
}

fail() {
  printf 'render helm values: %s\n' "$*" >&2
  exit 2
}

digest_re='^sha256:[0-9a-f]{64}$'
# tags are printed into YAML and into the asset name, so keep them to the
# characters a SemVer version can contain.
tag_re='^[0-9A-Za-z][0-9A-Za-z.+_-]*$'
# registry/repository names are lowercase; requiring an alphanumeric at both
# ends keeps a stray leading or trailing separator out of the image reference.
repository_re='^[a-z0-9]([a-z0-9./_-]*[a-z0-9])?$'
repository=ghcr.io/eimsound/lazy-observe
tag=
digest=
output=

while (($# > 0)); do
  case $1 in
  --repository)
    (($# >= 2)) || { usage; exit 2; }
    repository=$2
    shift 2
    ;;
  --tag)
    (($# >= 2)) || { usage; exit 2; }
    tag=$2
    shift 2
    ;;
  --digest)
    (($# >= 2)) || { usage; exit 2; }
    digest=$2
    shift 2
    ;;
  --output)
    (($# >= 2)) || { usage; exit 2; }
    output=$2
    shift 2
    ;;
  -h | --help)
    usage
    exit 0
    ;;
  *)
    usage
    exit 2
    ;;
  esac
done

[[ -n $tag ]] || fail '--tag is required and must not be empty'
[[ $tag =~ $tag_re ]] || fail "--tag must look like a released version, got '$tag'"
[[ -n $digest ]] || fail '--digest is required and must not be empty'
[[ $digest =~ $digest_re ]] || \
  fail "--digest must be \"sha256:\" followed by 64 lowercase hex characters, got '$digest'"
[[ -n $repository ]] || fail '--repository must not be empty'
[[ $repository =~ $repository_re ]] ||
  fail "--repository must be a lowercase registry/repository name, got '$repository'"

render() {
  printf '# Generated by scripts/render-helm-release-values.sh from the image this\n'
  printf '# release published. Layer it on top of deploy/helm/lazy-observe; the digest,\n'
  printf '# not the tag, selects the image that runs.\n'
  printf 'image:\n'
  printf '  repository: "%s"\n' "$repository"
  printf '  tag: "%s"\n' "$tag"
  printf '  digest: "%s"\n' "$digest"
}

if [[ -n $output ]]; then
  mkdir -p -- "$(dirname -- "$output")"
  render >"$output"
else
  render
fi
