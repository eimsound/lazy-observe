#!/usr/bin/env bash
set -euo pipefail
# 固定字节序排序：生成与 --check 必须在任何 locale（本机 zh_CN、CI 的 C.UTF-8）下得到同一份文件。
export LC_ALL=C

# Generate (or with --check, verify) web/THIRD_PARTY_LICENSES.md from the
# production dependency graph of web/. Keeps curated attribution/provenance
# notes synchronized with resolved versions and maintains a complete sorted
# inventory table so dependency upgrades cannot silently drift.

usage() {
  printf 'usage: %s [--check] [--license-json <file>]\n' "${0##*/}" >&2
}

mode=generate
license_json=
while (($# > 0)); do
  case $1 in
    --check)
      mode=check
      shift
      ;;
    --license-json)
      (($# >= 2)) || { usage; exit 2; }
      license_json=$2
      shift 2
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      usage
      exit 2
      ;;
  esac
done

root=$(CDPATH='' cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)
cd "$root"
output=web/THIRD_PARTY_LICENSES.md

command -v node >/dev/null 2>&1 || {
  printf 'missing node command required to generate %s\n' "$output" >&2
  exit 1
}

work=$(mktemp -d "${TMPDIR:-/tmp}/lazy-observe-web-notices.XXXXXX")
trap 'rm -rf -- "$work"' EXIT HUP INT TERM

if [[ -z $license_json ]]; then
  pnpm_command=${PNPM:-pnpm}
  command -v "$pnpm_command" >/dev/null 2>&1 || {
    printf 'missing pnpm command: %s\n' "$pnpm_command" >&2
    exit 1
  }
  license_json="$work/web-licenses.json"
  if ! (cd web && "$pnpm_command" licenses list --prod --json --recursive) >"$license_json"; then
    printf 'failed to list production dependency licenses for web\n' >&2
    exit 1
  fi
fi

LICENSE_JSON="$license_json" OUTPUT_FILE="$work/THIRD_PARTY_LICENSES.md" node <<'NODE'
const fs = require("node:fs");

const asciiCmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

const raw = fs.readFileSync(process.env.LICENSE_JSON, "utf8");
if (raw.trim() === "") {
  console.error("FAIL: web: pnpm produced empty license output");
  process.exit(1);
}

let groups;
try {
  groups = JSON.parse(raw);
} catch (error) {
  console.error(`FAIL: web: invalid license JSON: ${error.message}`);
  process.exit(1);
}
if (groups === null || Array.isArray(groups) || typeof groups !== "object") {
  console.error("FAIL: web: pnpm license JSON must be an object grouped by license");
  process.exit(1);
}

const byPackage = new Map();
for (const license of Object.keys(groups).sort(asciiCmp)) {
  const packages = groups[license];
  if (!Array.isArray(packages)) {
    continue;
  }
  for (const dep of packages) {
    if (!dep || typeof dep.name !== "string" || dep.name === "") {
      continue;
    }
    const versions = Array.isArray(dep.versions)
      ? dep.versions.filter((v) => typeof v === "string" && v !== "")
      : [];
    const declared = typeof dep.license === "string" && dep.license !== "" ? dep.license : license;
    if (!byPackage.has(dep.name)) {
      byPackage.set(dep.name, { versions: new Set(), licenses: new Set() });
    }
    const entry = byPackage.get(dep.name);
    for (const v of versions) {
      entry.versions.add(v);
    }
    if (declared) {
      entry.licenses.add(declared);
    }
  }
}

if (byPackage.size === 0) {
  console.error("FAIL: web: no production dependencies found in license JSON");
  process.exit(1);
}

const requireSingleVersion = (pkg) => {
  const entry = byPackage.get(pkg);
  if (!entry || entry.versions.size === 0) {
    console.error(`FAIL: web: expected attributed package ${pkg} in production dependencies`);
    process.exit(1);
  }
  return Array.from(entry.versions).sort(asciiCmp).join(", ");
};

const promqlVersion = requireSingleVersion("@prometheus-io/lezer-promql");
const uplotVersion = requireSingleVersion("uplot");
const dayjsVersion = requireSingleVersion("dayjs");
const codemirrorPackages = [
  "@codemirror/autocomplete",
  "@codemirror/commands",
  "@codemirror/language",
  "@codemirror/state",
  "@codemirror/view",
  "@lezer/highlight",
];
const codemirrorLines = codemirrorPackages.map((pkg) => `- \`${pkg}\` ${requireSingleVersion(pkg)}`);

const inventoryLines = Array.from(byPackage.keys())
  .sort(asciiCmp)
  .map((pkg) => {
    const entry = byPackage.get(pkg);
    const versions = Array.from(entry.versions).sort(asciiCmp).join(", ");
    const licenses = Array.from(entry.licenses).sort(asciiCmp).join(", ");
    return `| \`${pkg}\` | ${versions} | ${licenses} |`;
  });

const content = [
  "# Web third-party licenses",
  "",
  "<!-- Generated by scripts/web-third-party-licenses.sh; do not edit by hand. -->",
  "",
  "## Attribution and provenance notes",
  "",
  "The production web application includes the following Prometheus-maintained",
  "package for the PromQL query tree and Explain view:",
  "",
  `- \`@prometheus-io/lezer-promql\` ${promqlVersion}`,
  "",
  "Copyright 2021 The Prometheus Authors.",
  "",
  "These packages are licensed under the Apache License, Version 2.0. Their full",
  "license text is distributed in each npm package as `LICENSE` and is available",
  "from <https://www.apache.org/licenses/LICENSE-2.0>.",
  "",
  "The MetricsQL input uses the following CodeMirror 6 packages under the MIT",
  "license:",
  "",
  ...codemirrorLines,
  "",
  "Their license texts are distributed in the corresponding npm packages.",
  "",
  `The metrics time-series charts and logs histograms use \`uplot\` ${uplotVersion},`,
  "Copyright (c) 2019 Leon Sorokin, under the MIT license. The full license text",
  "is distributed in the npm package as `LICENSE`.",
  "",
  `Date parsing, formatting, localization, and timezone handling use \`dayjs\` ${dayjsVersion},`,
  "Copyright (c) 2018-present, iamkun, under the MIT license. The application statically",
  "includes only the English and Simplified Chinese locale modules. The full license text",
  "is distributed in the npm package as `LICENSE`.",
  "",
  "The query-workspace layout and application state in lazy-observe were rewritten",
  "for this project after reviewing Prometheus' Expression Browser behavior; no",
  "Prometheus QueryPage, QueryPanel, graph, table, or metrics-explorer source file",
  "was copied into this repository. The MetricsQL editor integration and its",
  "project-scoped completion behavior are implemented in this repository rather",
  "than using Prometheus' CodeMirror editor or linter.",
  "",
  "The logs explorer was independently implemented for lazy-observe after",
  "reviewing the VictoriaLogs UI Query page from the Apache-2.0-licensed",
  "VictoriaLogs repository. No VictoriaLogs UI source file or runtime dependency",
  "is copied or bundled into this application; the implementation uses the",
  "project's existing React, CodeMirror, and uPlot stack and communicates only",
  "through lazy-observe's project-scoped gateway routes.",
  "",
  "## Production dependency inventory",
  "",
  "| Package | Version | License |",
  "| --- | --- | --- |",
  ...inventoryLines,
  "",
].join("\n");

fs.writeFileSync(process.env.OUTPUT_FILE, content, "utf8");
NODE

if [[ $mode == check ]]; then
  if [[ ! -f $output ]]; then
    printf '%s is missing; run: mise run web-third-party-licenses\n' "$output" >&2
    exit 1
  fi
  if ! cmp -s "$work/THIRD_PARTY_LICENSES.md" "$output"; then
    printf '%s is stale; run: mise run web-third-party-licenses\n' "$output" >&2
    diff -u "$output" "$work/THIRD_PARTY_LICENSES.md" | head -40 >&2 || true # pipefail-ok: 只截取诊断输出，退出码由 || true 吸收
    exit 1
  fi
  printf 'PASS: %s matches the production web dependency graph\n' "$output"
  exit 0
fi

cp "$work/THIRD_PARTY_LICENSES.md" "$output"
printf 'wrote %s\n' "$output"
