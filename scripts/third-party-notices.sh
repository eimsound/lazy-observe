#!/usr/bin/env bash
set -euo pipefail
# 固定字节序排序：生成与 --check 必须在任何 locale（本机 zh_CN、CI 的 C.UTF-8）下得到同一份文件。
export LC_ALL=C

# Generate (or with --check, verify) the Go third-party notices shipped in
# release archives and container images. The notice covers every module linked
# into ./cmd/lazy-observe on both release targets and embeds each license text
# from the Go module cache, so the output only changes when go.mod/go.sum do.

usage() {
  printf 'usage: %s [--check]\n' "${0##*/}" >&2
}

mode=generate
case $# in
  0) ;;
  1)
    [[ $1 == --check ]] || { usage; exit 2; }
    mode=check
    ;;
  *)
    usage
    exit 2
    ;;
esac

root=$(CDPATH='' cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)
cd "$root"
output=third_party/go/THIRD_PARTY_NOTICES.txt
main_module=$(go list -m -f '{{.Path}}')

work=$(mktemp -d "${TMPDIR:-/tmp}/lazy-observe-notices.XXXXXX")
trap 'rm -rf -- "$work"' EXIT HUP INT TERM

printf '{{range .}}{{.Name}}\t{{.Version}}\t{{.LicenseName}}\t{{.LicensePath}}\n{{end}}' >"$work/report.tpl"
for platform in linux/amd64 linux/arm64; do
  CGO_ENABLED=0 GOOS=${platform%/*} GOARCH=${platform#*/} \
    go-licenses report ./cmd/lazy-observe \
      --template "$work/report.tpl" \
      --ignore="$main_module" \
      2>"$work/report.err" >>"$work/report.tsv" || {
    cat "$work/report.err" >&2
    printf 'go-licenses report failed for %s\n' "$platform" >&2
    exit 1
  }
done
sort -u "$work/report.tsv" >"$work/report.sorted"

{
  printf 'lazy-observe third-party notices (Go)\n'
  printf '======================================\n\n'
  printf 'The lazy-observe binary links the Go packages listed below. Each group\n'
  printf 'is followed by the full license text shipped with that module.\n'
  printf 'Generated by scripts/third-party-notices.sh; do not edit by hand.\n'
  # Group packages by the license file they share (one file per module).
  cut -f4 "$work/report.sorted" | sort -u | while IFS= read -r license_path; do
    [[ -n $license_path ]] || continue
    [[ -f $license_path ]] || {
      printf 'license file not found: %s\n' "$license_path" >&2
      exit 1
    }
    printf '\n------------------------------------------------------------------------\n'
    awk -F'\t' -v path="$license_path" \
      '$4 == path { printf "%s %s (%s)\n", $1, $2, $3 }' "$work/report.sorted"
    printf '\n'
    cat -- "$license_path"
  done
} >"$work/notices.txt"

if [[ $mode == check ]]; then
  # Embedded Victoria binaries: the shipped license copies must match the pins.
  for var in metrics_version logs_version traces_version; do
    version=$(sed -n "s/^${var}=//p" scripts/download-storage-bins.sh)
    [[ -n $version ]] || { printf 'cannot read %s from download-storage-bins.sh\n' "$var" >&2; exit 1; }
    grep -Fq -- " $version " third_party/victoria/SOURCES.txt || {
      printf 'third_party/victoria/SOURCES.txt does not list pinned %s=%s\n' "$var" "$version" >&2
      exit 1
    }
  done
  for repo in VictoriaMetrics VictoriaLogs VictoriaTraces; do
    [[ -s third_party/victoria/$repo/LICENSE ]] || {
      printf 'missing third_party/victoria/%s/LICENSE\n' "$repo" >&2
      exit 1
    }
  done
  if ! cmp -s "$work/notices.txt" "$output"; then
    printf '%s is stale; run: mise run third-party-notices\n' "$output" >&2
    diff -u "$output" "$work/notices.txt" | head -40 >&2 || true # pipefail-ok: 只截取诊断输出，退出码由 || true 吸收
    exit 1
  fi
  printf 'PASS: %s matches the linked Go dependency graph\n' "$output"
  exit 0
fi

mkdir -p "$(dirname -- "$output")"
cp "$work/notices.txt" "$output"
printf 'wrote %s\n' "$output"
